// ---- tiny label formatters (avoid importing fmt just for %g spread) ----

func fmtf(name string, x float64) string {
	return name + "(" + g64(x) + ")"
}
func fmtf2(name string, x, y float64) string {
	return name + "(" + g64(x) + ", " + g64(y) + ")"
}
func fmtf32(name string, x float32) string {
	return name + "(" + g64(float64(x)) + ")"
}
func fmtf322(name string, x, y float32) string {
	return name + "(" + g64(float64(x)) + ", " + g64(float64(y)) + ")"
}
func g64(x float64) string {
	return strconv.FormatFloat(x, 'g', -1, 64)
}
