// math_pow_test.go — cross-checks the "pow" cluster (pow/sqrt/cbrt/hypot + f
// variants). sqrt/sqrtf are hardware correctly-rounded, so they must match
// Go's math.Sqrt bit-exactly. The transcendental pow/cbrt/hypot (and their
// float variants) are compared against a correctly-rounded high-precision
// oracle (mpmath, see math_oracle_test.go) instead of Go's math package: Go's
// pow is wrong by up to ~1000 ULP at the extreme-exponent inputs here while
// the port is correctly rounded, so Go is a bad reference. Finite in-domain
// inputs use the oracle at a tight ULP bound; special/edge inputs (Inf, NaN,
// ±0 bases, negative-base non-integer exponents) are absent from the oracle
// and fall back to Go's math, which is exact for them.
//
// NOTE: the Go bindings (Pow, Powf, Sqrt, Sqrtf, Cbrt, Cbrtf, Hypot, Hypotf)
// are generated by gen.sh, so this file does not compile until then. That is
// expected.
package libc

import (
	"math"
	"strconv"
	"testing"
)

// ---- ULP distance helpers (total-order monotonic mapping) ----

func mono64(f float64) uint64 {
	b := math.Float64bits(f)
	if b>>63 == 1 {
		return ^b
	}
	return b + (1 << 63)
}

func powUlp64(a, b float64) uint64 {
	ma, mb := mono64(a), mono64(b)
	if ma > mb {
		return ma - mb
	}
	return mb - ma
}

func mono32(f float32) uint32 {
	b := math.Float32bits(f)
	if b>>31 == 1 {
		return ^b
	}
	return b + (1 << 31)
}

func powUlp32(a, b float32) uint32 {
	ma, mb := mono32(a), mono32(b)
	if ma > mb {
		return ma - mb
	}
	return mb - ma
}

func chk64(t *testing.T, label string, got, want float64, tol uint64) {
	t.Helper()
	if math.IsNaN(got) && math.IsNaN(want) {
		return
	}
	if d := powUlp64(got, want); d > tol {
		t.Errorf("%s = %v (%#016x), want %v (%#016x); ulp diff %d > %d",
			label, got, math.Float64bits(got), want, math.Float64bits(want), d, tol)
	}
}

func chk32(t *testing.T, label string, got, want float32, tol uint32) {
	t.Helper()
	if math.IsNaN(float64(got)) && math.IsNaN(float64(want)) {
		return
	}
	if d := powUlp32(got, want); d > tol {
		t.Errorf("%s = %v (%#08x), want %v (%#08x); ulp diff %d > %d",
			label, got, math.Float32bits(got), want, math.Float32bits(want), d, tol)
	}
}

// A broad spread of double inputs: 0, -0, ±1, subnormals, min-normal, large,
// small, ±Inf, NaN, and assorted normals.
var powDvals = []float64{
	0.0,
	math.Copysign(0, -1),
	1.0, -1.0, 2.0, -2.0, 0.5, -0.5,
	3.14159265358979, -3.14159265358979,
	123456.789, -987654.321,
	1e300, 1e-300,
	math.MaxFloat64,
	2.2250738585072014e-308, // smallest normal
	5e-324,                  // smallest subnormal
	8.0, 27.0, -64.0, 1000000.0,
	math.Inf(1), math.Inf(-1), math.NaN(),
}

var powFvals = []float32{
	0.0,
	float32(math.Copysign(0, -1)),
	1.0, -1.0, 2.0, -2.0, 0.5, -0.5,
	3.14159265, -3.14159265,
	12345.678, -98765.4,
	1e30, 1e-30,
	math.MaxFloat32,
	1.1754944e-38, // smallest normal float32
	1.4e-45,       // smallest subnormal float32
	8.0, 27.0, -64.0, 1000000.0,
	float32(math.Inf(1)), float32(math.Inf(-1)), float32(math.NaN()),
}

// ---- sqrt / sqrtf : correctly rounded, must be bit-exact ----

func TestSqrt(t *testing.T) {
	for _, x := range powDvals {
		chk64(t, fmtf("Sqrt", x), Sqrt(x), math.Sqrt(x), 0)
	}
}

func TestSqrtf(t *testing.T) {
	for _, x := range powFvals {
		want := float32(math.Sqrt(float64(x)))
		chk32(t, fmtf32("Sqrtf", x), Sqrtf(x), want, 0)
	}
}

