var dpairs = [][2]float64{
	{2, 3}, {2, 0.5}, {2, -0.5}, {2, -3}, {10, 10}, {0.5, 20},
	{3, 100}, {2, 1023}, {2, -1023}, {1.5, 2.7}, {123.456, 0.333},
	{0.9999, 10000}, {1.0001, 5000}, {7, 7}, {2.5, 4},
	// integer-exponent negatives
	{-2, 3}, {-2, 2}, {-8, 0.3333333333333333}, {-2, 2.5}, // last -> NaN
	// special: x==±0
	{0, 3}, {0, -3}, {math.Copysign(0, -1), 3}, {math.Copysign(0, -1), -3},
	{0, 4}, {0, -4},
	// special: exponent 0 / 1, base 1
	{2, 0}, {math.NaN(), 0}, {2, 1}, {1, 1e300}, {-1, 1e300}, {1, math.NaN()},
	// infinities
	{math.Inf(1), 2}, {math.Inf(1), -2}, {math.Inf(-1), 3}, {math.Inf(-1), -3},
	{2, math.Inf(1)}, {0.5, math.Inf(1)}, {2, math.Inf(-1)}, {0.5, math.Inf(-1)},
	{-1, math.Inf(1)},
	// NaN
	{math.NaN(), 2}, {2, math.NaN()},
	// over/underflow
	{1e300, 2}, {1e-300, 2},
}

func TestPow(t *testing.T) {
	for _, p := range dpairs {
		x, y := p[0], p[1]
		chk64(t, fmtf2("Pow", x, y), Pow(x, y), powRef(x, y), 2)
	}
}

